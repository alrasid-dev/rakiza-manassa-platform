const RIYADH_OFFSET_MS = 3 * 60 * 60 * 1000;

function toDate(value: unknown): Date | null {
  if (!value) return null;
  const d = value instanceof Date ? value : new Date(value as string | number);
  return Number.isNaN(d.getTime()) ? null : d;
}

function riyadhDateKey(value: unknown): string {
  const d = toDate(value);
  if (!d) return "";
  return new Date(d.getTime() + RIYADH_OFFSET_MS).toISOString().slice(0, 10);
}

function parseDayKey(key: string): Date | null {
  const [y, m, d] = key.split("-").map(Number);
  if (!y || !m || !d) return null;
  return new Date(Date.UTC(y, m - 1, d));
}

function round1(n: number): number {
  return Math.round(n * 10) / 10;
}

function round2(n: number): number {
  return Math.round(n * 100) / 100;
}

function percent(part: number, whole: number): number {
  return whole > 0 ? round1((part / whole) * 100) : 0;
}

function bump(map: Map<string, number>, key: string): void {
  if (!key) return;
  map.set(key, (map.get(key) ?? 0) + 1);
}

function* eachDay(startKey: string, endKey: string): Generator<string> {
  const start = parseDayKey(startKey);
  const end = parseDayKey(endKey);
  if (!start || !end) return;
  const cursor = new Date(start);
  while (cursor.getTime() <= end.getTime()) {
    yield cursor.toISOString().slice(0, 10);
    cursor.setUTCDate(cursor.getUTCDate() + 1);
  }
}

function daysBetween(startKey: string, endKey: string): number {
  const start = parseDayKey(startKey);
  const end = parseDayKey(endKey);
  if (!start || !end) return 0;
  return Math.max(1, Math.round((end.getTime() - start.getTime()) / 86400000) + 1);
}

export interface KpiDailyFlowRow {
  date: string;
  newTasks: number;
  completedTasks: number;
  attendance: number;
  leaves: number;
}

export interface KpiReport {
  periodStart: string;
  periodEnd: string;
  units: { total: number; active: number; activeBoth: number; empty: number; noTemplates: number };
  employees: { total: number; active: number };
  tasks: { total: number; completed: number; overdue: number; inProgress: number; autoGenerated: number; manual: number; archived: number };
  completionRate: number;
  attendance: { total: number; complianceRate: number };
  leaves: { total: number; approved: number; rejected: number; pending: number };
  accountabilityTargetRate: number;
  totalArchived: number;
  averages: { tasksPerUnit: number; tasksPerEmployeePerDay: number; avgCompletionHours: number | null; completedPerDay: number; productivity: number };
  automationRate: number;
  predictions: { daily: number; monthly: number; yearly: number };
  dailyFlow: KpiDailyFlowRow[];
}

export async function buildKpiReport(): Promise<KpiReport> {
  const db = await getDb();
  const now = new Date();
  const monthStart = reportStart("monthly", now);
  const periodStartKey = riyadhDateKey(monthStart);
  const periodEndKey = riyadhDateKey(now);

  const units = db ? await db.select().from(organizationUnits) : [];
  const profiles = db ? await db.select().from(personProfiles) : [];
  const templates = db ? await db.select().from(taskTemplates) : [];
  const allTasks = db ? await db.select().from(tasks) : [];
  const attendance = db ? await db.select().from(attendanceRecords) : [];
  const leaves = db ? await db.select().from(leaveRequests) : [];

  let attendanceArchiveCount = 0;
  if (db) {
    try {
      const result = await db.execute(sql`SELECT COUNT(*) AS c FROM attendance_records_archive`);
      const rows = Array.isArray(result) ? result[0] : (result as { rows?: unknown[] }).rows;
      const row = (rows as Array<{ c?: number | string }> | undefined)?.[0];
      attendanceArchiveCount = Number(row?.c ?? 0);
    } catch {
      attendanceArchiveCount = 0;
    }
  }

  const activeUnits = units.filter(u => u.isActive);
  const activeProfiles = profiles.filter(p => p.status === "active");
  const activeTemplates = templates.filter(t => t.isActive);
  const unitIdsWithStaff = new Set(activeProfiles.map(p => p.unitId).filter((id): id is number => id != null));
  const unitIdsWithTemplates = new Set(activeTemplates.map(t => t.unitId).filter((id): id is number => id != null));
  const activeBoth = activeUnits.filter(u => unitIdsWithStaff.has(u.id) && unitIdsWithTemplates.has(u.id));
  const emptyUnits = activeUnits.filter(u => !unitIdsWithStaff.has(u.id) && !unitIdsWithTemplates.has(u.id));
  const noTemplateUnits = activeUnits.filter(u => !unitIdsWithTemplates.has(u.id));

  const completed = allTasks.filter(t => t.status === "completed");
  const overdue = allTasks.filter(t => t.status === "overdue");
  const inProgress = allTasks.filter(t => ["new", "in_progress", "under_review", "paused"].includes(t.status));
  const autoGenerated = allTasks.filter(t => t.templateId != null);
  const manualTasks = allTasks.filter(t => t.templateId == null);
  const archivedTasks = allTasks.filter(t => t.archivedAt != null);

  const present = attendance.filter(a => a.status === "present");
  const late = attendance.filter(a => a.status === "late");

  const newTasksInPeriod = allTasks.filter(t => {
    const c = toDate(t.createdAt);
    return c != null && c >= monthStart;
  });
  const completedInPeriod = allTasks.filter(t => {
    const c = toDate(t.completedAt);
    return c != null && c >= monthStart;
  });

  const daysElapsed = daysBetween(periodStartKey, periodEndKey);
  const activeCount = activeProfiles.length;

  const hoursList: number[] = [];
  for (const t of completed) {
    const created = toDate(t.createdAt);
    const done = toDate(t.completedAt) ?? toDate(t.updatedAt);
    if (created && done) {
      const h = (done.getTime() - created.getTime()) / 36e5;
      if (h > 0 && h < 720) hoursList.push(h);
    }
  }
  const avgCompletionHours = hoursList.length ? round1(hoursList.reduce((a, b) => a + b, 0) / hoursList.length) : null;

  const X = activeBoth.length;
  const Y = units.length - X;
  const Z = X > 0 && daysElapsed > 0 ? newTasksInPeriod.length / daysElapsed / X : 0;
  const dailyPrediction = Math.round((X + Y) * Z * 0.75);

  const createdByDay = new Map<string, number>();
  const completedByDay = new Map<string, number>();
  const attendanceByDay = new Map<string, number>();
  const leavesByDay = new Map<string, number>();
  for (const t of allTasks) {
    bump(createdByDay, riyadhDateKey(t.createdAt));
    bump(completedByDay, riyadhDateKey(t.completedAt));
  }
  for (const a of attendance) bump(attendanceByDay, riyadhDateKey(a.recordDate));
  for (const l of leaves) bump(leavesByDay, riyadhDateKey(l.startAt));

  const dailyFlow: KpiDailyFlowRow[] = [];
  for (const day of eachDay(periodStartKey, periodEndKey)) {
    dailyFlow.push({
      date: day,
      newTasks: createdByDay.get(day) ?? 0,
      completedTasks: completedByDay.get(day) ?? 0,
      attendance: attendanceByDay.get(day) ?? 0,
      leaves: leavesByDay.get(day) ?? 0,
    });
  }

  return {
    periodStart: periodStartKey,
    periodEnd: periodEndKey,
    units: {
      total: units.length,
      active: activeUnits.length,
      activeBoth: X,
      empty: emptyUnits.length,
      noTemplates: noTemplateUnits.length,
    },
    employees: { total: profiles.length, active: activeCount },
    tasks: {
      total: allTasks.length,
      completed: completed.length,
      overdue: overdue.length,
      inProgress: inProgress.length,
      autoGenerated: autoGenerated.length,
      manual: manualTasks.length,
      archived: archivedTasks.length,
    },
    completionRate: percent(completed.length, allTasks.length),
    attendance: { total: attendance.length, complianceRate: percent(present.length + late.length, attendance.length) },
    leaves: {
      total: leaves.length,
      approved: leaves.filter(l => l.status === "approved").length,
      rejected: leaves.filter(l => l.status === "rejected").length,
      pending: leaves.filter(l => l.status === "pending").length,
    },
    accountabilityTargetRate: 10,
    totalArchived: archivedTasks.length + attendanceArchiveCount,
    averages: {
      tasksPerUnit: units.length ? round1(allTasks.length / units.length) : 0,
      tasksPerEmployeePerDay: daysElapsed > 0 && activeCount > 0 ? round2(newTasksInPeriod.length / daysElapsed / activeCount) : 0,
      avgCompletionHours,
      completedPerDay: daysElapsed > 0 ? round1(completedInPeriod.length / daysElapsed) : 0,
      productivity: daysElapsed > 0 && activeCount > 0 ? round2(completedInPeriod.length / daysElapsed / activeCount) : 0,
    },
    automationRate: percent(autoGenerated.length, allTasks.length),
    predictions: { daily: dailyPrediction, monthly: dailyPrediction * 30, yearly: dailyPrediction * 365 },
    dailyFlow,
  };
}

const BRAND = {
  green: "3F7354",
  greenStrong: "245F43",
  greenSoft: "DCE9DA",
  gold: "B18448",
  ink: "243D32",
  cream: "F8F8F3",
  white: "FFFFFF",
};

function cellRef(row: number, col: number): string {
  const letters = "ABCDEFGHIJKLMNOPQRSTUVWXYZ";
  let c = col;
  let ref = "";
  while (c >= 0) {
    ref = letters[c % 26] + ref;
    c = Math.floor(c / 26) - 1;
  }
  return `${ref}${row + 1}`;
}

function applyCellStyle(ws: XLSX.WorkSheet, row: number, col: number, opts: { fill?: string; color?: string; bold?: boolean; sz?: number; align?: "left" | "center" | "right" }) {
  const target = (ws as Record<string, unknown>)[cellRef(row, col)] as { s?: Record<string, unknown> } | undefined;
  if (!target) return;
  target.s = {
    font: { name: "Calibri", sz: opts.sz ?? 11, bold: !!opts.bold, color: opts.color ? { rgb: opts.color } : { rgb: BRAND.ink } },
    ...(opts.fill ? { fill: { patternType: "solid", fgColor: { rgb: opts.fill } } } : {}),
    ...(opts.align ? { alignment: { horizontal: opts.align } } : {}),
  };
}

export async function buildKpiWorkbook(): Promise<{ buffer: Buffer; filename: string }> {
  const r = await buildKpiReport();

  const metrics: Array<[string, string | number]> = [
    ["عدد الأقسام الكلية", r.units.total],
    ["الأقسام الفعّالة", r.units.activeBoth],
    ["الأقسام الفارغة", r.units.empty],
    ["الأقسام بلا قوالب", r.units.noTemplates],
    ["الموظفون النشطون", r.employees.active],
    ["الموظفون الكلي", r.employees.total],
    ["إجمالي المهام", r.tasks.total],
    ["المهام المكتملة", r.tasks.completed],
    ["المهام المتأخرة", r.tasks.overdue],
    ["المهام الجارية", r.tasks.inProgress],
    ["مستوى الإنجاز %", r.completionRate],
    ["إجمالي تسجيلات الحضور", r.attendance.total],
    ["نسبة الالتزام %", r.attendance.complianceRate],
    ["إجمالي الإجازات", r.leaves.total],
    ["الإجازات المعتمدة", r.leaves.approved],
    ["الإجازات المرفوضة", r.leaves.rejected],
    ["الإجازات المعلقة", r.leaves.pending],
    ["معدل المساءلات المستهدف %", r.accountabilityTargetRate],
    ["إجمالي المؤرشف", r.totalArchived],
    ["متوسط المهام لكل قسم", r.averages.tasksPerUnit],
    ["متوسط المهام لكل موظف/يوم", r.averages.tasksPerEmployeePerDay],
    ["متوسط وقت إنهاء المهمة (ساعة)", r.averages.avgCompletionHours ?? 0],
    ["متوسط المهام المنجزة/يوم", r.averages.completedPerDay],
    ["معدل الإنتاجية", r.averages.productivity],
    ["المهام المُولَّدة تلقائياً", r.tasks.autoGenerated],
    ["المهام اليدوية", r.tasks.manual],
    ["نسبة الأتمتة %", r.automationRate],
    ["مهام متوقعة (يومي)", r.predictions.daily],
    ["مهام متوقعة (شهري)", r.predictions.monthly],
    ["مهام متوقعة (سنوي)", r.predictions.yearly],
  ];
  const colCount = metrics.length;

  // الورقة 1: KPI — أفقية (كل مؤشر عمود).
  const kpiAoa: Array<Array<string | number>> = [
    ["رَكيزة — تقرير مؤشرات الأداء KPI"],
    [`الفترة: ${r.periodStart} → ${r.periodEnd}`],
    metrics.map(m => m[0]),
    metrics.map(m => m[1]),
  ];
  const kpiWs = XLSX.utils.aoa_to_sheet(kpiAoa);
  kpiWs["!cols"] = Array.from({ length: colCount }, () => ({ wch: 20 }));
  (kpiWs as Record<string, unknown>)["!merges"] = [
    { s: { r: 0, c: 0 }, e: { r: 0, c: colCount - 1 } },
    { s: { r: 1, c: 0 }, e: { r: 1, c: colCount - 1 } },
  ];
  applyCellStyle(kpiWs, 0, 0, { fill: BRAND.green, color: BRAND.white, bold: true, sz: 14, align: "center" });
  applyCellStyle(kpiWs, 1, 0, { fill: BRAND.greenStrong, color: BRAND.gold, bold: true, align: "center" });
  for (let c = 0; c < colCount; c++) {
    applyCellStyle(kpiWs, 2, c, { fill: BRAND.green, color: BRAND.gold, bold: true });
    applyCellStyle(kpiWs, 3, c, { fill: BRAND.cream, color: BRAND.ink });
  }

  // الورقة 2: DailyFlow — عمودية (سلسلة زمنية).
  const flowAoa: Array<Array<string | number>> = [["التاريخ", "مهام جديدة", "مهام منجزة", "حضور", "إجازات"]];
  let totalNew = 0;
  let totalDone = 0;
  let totalAttendance = 0;
  let totalLeaves = 0;
  for (const row of r.dailyFlow) {
    flowAoa.push([row.date, row.newTasks, row.completedTasks, row.attendance, row.leaves]);
    totalNew += row.newTasks;
    totalDone += row.completedTasks;
    totalAttendance += row.attendance;
    totalLeaves += row.leaves;
  }
  flowAoa.push(["الإجمالي", totalNew, totalDone, totalAttendance, totalLeaves]);
  const flowWs = XLSX.utils.aoa_to_sheet(flowAoa);
  flowWs["!cols"] = [{ wch: 14 }, { wch: 12 }, { wch: 12 }, { wch: 10 }, { wch: 10 }];
  for (let c = 0; c < 5; c++) applyCellStyle(flowWs, 0, c, { fill: BRAND.green, color: BRAND.gold, bold: true });
  const flowLast = flowAoa.length - 1;
  for (let c = 0; c < 5; c++) applyCellStyle(flowWs, flowLast, c, { fill: BRAND.cream, color: BRAND.ink, bold: true });

  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, kpiWs, "KPI");
  XLSX.utils.book_append_sheet(wb, flowWs, "DailyFlow");
  const buffer = XLSX.write(wb, { type: "buffer", bookType: "xlsx", cellStyles: true }) as Buffer;
  return { buffer, filename: `rakiza_kpi_${r.periodEnd}.xlsx` };
}


