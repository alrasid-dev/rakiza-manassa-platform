/**
 * تقرير KPI للمالك — ورقة Excel واحدة (KPI).
 * يجمع المؤشرات من قاعدة البيانات ويبني 5 أقسام + تدفق يومي + توقعات بالقياس الخطي، بهوية المنصة.
 */
